const siv::PerlinNoise perlin;

constexpr int MAX_RAYCAST_STEPS = 128;

voxelSphere::voxelSphere(glm::vec3 inPosition, float inRadius, VkDeviceSize inOffset) {
    model.position = inPosition;
    currentRadius = inRadius;
    realRadius = inRadius;

    scale = glm::uvec3((inRadius + 2) * 2);
    grid = new float[scale.x * scale.y * scale.z];
    center = (glm::vec3)scale / glm::vec3(2);
    offset = inOffset;

    model.verticesOffset = inOffset * sizeof(model.vertices[0]);
    model.indicesOffset = inOffset * sizeof(model.indices[0]);
    model.maxSize = scale.x * scale.y * scale.z * 15;
}

modelData voxelSphere::generateSphere() {
    for (uint32_t x = 0; x < scale.x; x++) {
        for (uint32_t y = 0; y < scale.y; y++) {
            for (uint32_t z = 0; z < scale.z; z++) {
                float xGap = x - center.x;
                float yGap = y - center.y;
                float zGap = z - center.z;
                float distance = std::sqrt(xGap * xGap + yGap * yGap + zGap * zGap);

                getVoxel({ x, y, z }) = currentRadius - distance;
            }
        }
    }

    updateMarchingCubes();

    return model;
}

modelData voxelSphere::updateMarchingCubes() {
    model.vertices.clear();
    model.indices.clear();

    for (uint32_t x = 0; x < scale.x - 1; x++) {
        for (uint32_t y = 0; y < scale.y - 1; y++) {
            for (uint32_t z = 0; z < scale.z - 1; z++) {
                processCube({ x, y, z });
            }
        }
    }

    return model;
}

modelData voxelSphere::getData() {
    return model;
}

bool voxelSphere::shouldUpdate() {
    bool check = abs(currentRadius - realRadius) > updatePoint;
    if (check)
        currentRadius = realRadius;

    return check;
}

float& voxelSphere::getVoxel(glm::uvec3 pos) {
	return grid[pos.x + pos.y * scale.x + pos.z * scale.x * scale.y];
}

void voxelSphere::addVertex(glm::vec3 pos, glm::vec3 normal, glm::vec3 color, glm::vec2 texCoord) {
    float ironContent = perlin.noise3D_01(pos.x * ironSize, pos.y * ironSize, pos.z * ironSize);
    if (ironContent < ironCutOff) ironContent = 0.0f;
    color = glm::vec3(0.5f) + glm::vec3(0.7f, 0.27f, 0.0f) * ironContent;

    pos = (pos + model.position - center) * voxelScale;

    Vertex vertex = { pos, normal, color, texCoord };

    model.indices.push_back(model.vertices.size() + offset);
    model.vertices.push_back(vertex);
}

void voxelSphere::processCube(glm::uvec3 pos) {
    glm::vec3 cornerCoords[8];
    cornerCoords[0] = pos;
    cornerCoords[1] = pos + glm::uvec3(1, 0, 0);
    cornerCoords[2] = pos + glm::uvec3(1, 0, 1);
    cornerCoords[3] = pos + glm::uvec3(0, 0, 1);
    cornerCoords[4] = pos + glm::uvec3(0, 1, 0);
    cornerCoords[5] = pos + glm::uvec3(1, 1, 0);
    cornerCoords[6] = pos + glm::uvec3(1, 1, 1);
    cornerCoords[7] = pos + glm::uvec3(0, 1, 1);

    int cubeConfig = 0;
    for (int i = 0; i < 8; i++) {
        if (getVoxel(cornerCoords[i]) < 0) {
            cubeConfig |= (1 << i);
        }
    }

    const int* edgeIndices = triangulation[cubeConfig];

    for (int i = 0; i < 16; i += 3) {
        if (edgeIndices[i] == -1) break;

        int a0 = cornerIndexAFromEdge[edgeIndices[i + 2]];
        int a1 = cornerIndexBFromEdge[edgeIndices[i + 2]];

        int b0 = cornerIndexAFromEdge[edgeIndices[i + 1]];
        int b1 = cornerIndexBFromEdge[edgeIndices[i + 1]];

        int c0 = cornerIndexAFromEdge[edgeIndices[i + 0]];
        int c1 = cornerIndexBFromEdge[edgeIndices[i + 0]];

        glm::vec3 vertAPos = (cornerCoords[a0] + cornerCoords[a1]) * 0.5f;
        glm::vec3 vertBPos = (cornerCoords[b0] + cornerCoords[b1]) * 0.5f;
        glm::vec3 vertCPos = (cornerCoords[c0] + cornerCoords[c1]) * 0.5f;

        glm::vec3 normal = computeNormal(vertAPos, vertBPos, vertCPos);

        addVertex(vertAPos, normal, glm::vec3(1.0f), glm::vec2(0.0f, 0.0f));
        addVertex(vertBPos, normal, glm::vec3(1.0f), glm::vec2(1.0f, 0.0f));
        addVertex(vertCPos, normal, glm::vec3(1.0f), glm::vec2(0.0f, 1.0f));
    }
}

glm::vec3 voxelSphere::computeNormal(glm::vec3 a, glm::vec3 b, glm::vec3 c) {
    return glm::normalize(glm::cross(b - a, c - a));
}

std::optional<float> voxelSphere::rayAABB(glm::vec3 gridMin, glm::vec3 gridMax, glm::vec3 origin, glm::vec3 direction) {
    float tmin = 0, tmax = 1e30f;

    for (int axis = 0; axis < 3; ++axis) {
        const float t1 = (gridMin[axis] - origin[axis]) / direction[axis];
        const float t2 = (gridMax[axis] - origin[axis]) / direction[axis];

        const float dmin = std::min(t1, t2);
        const float dmax = std::max(t1, t2);

        tmin = std::max(dmin, tmin);
        tmax = std::min(dmax, tmax);
    }
    if (tmax >= tmin) return tmin;
    return {};
}

// Gets the sign of a float (-1 or 1)
inline int getsign(const float f) { return 1 - (int)(((unsigned int&)f) >> 31) * 2; }

inline glm::vec3 signOfVec(const glm::vec3& v) {
    return glm::vec3(getsign(v.x), getsign(v.y), getsign(v.z));
}

rayCastHit voxelSphere::rayCast(glm::vec3 origin, glm::vec3 direction) {
    direction = normalize(direction);
    const glm::vec3 fscale = glm::vec3(scale);

    const glm::vec3 gridMin = (model.position - center) * voxelScale;
    const glm::vec3 gridMax = (fscale + model.position - center) * voxelScale;

    const std::optional<float> entryT = rayAABB(gridMin, gridMax, origin, direction);
    if (!entryT.has_value()) return rayCastMiss;

    const glm::vec3 voxelsPerUnit = fscale / (gridMax - gridMin);

    const glm::vec3 entryPos = ((origin + direction * (entryT.value() + 0.0001f)) - gridMin) * voxelsPerUnit;

    const glm::vec3 step = signOfVec(direction);
    const glm::vec3 delta = abs(1.0f / direction);

    glm::vec3 pos = clamp(floor(entryPos), glm::vec3(0.0f), fscale);

    /* Initialize the time along the ray when each axis crosses its next cell boundary */
    glm::vec3 tmax = (pos - entryPos + max(step, glm::vec3(0.0f))) / direction;

    int axis = 0;
    for (int steps = 0; steps < MAX_RAYCAST_STEPS; ++steps) {
        /* Check if we hit a voxel which isn't 0 */
        float& voxel = getVoxel(pos);
        if (voxel >= 0) {
            float ironContent = perlin.noise3D_01(pos.x * ironSize, pos.y * ironSize, pos.z * ironSize);
            if (ironContent < ironCutOff) ironContent = 0.0f;
            return rayCastHit(true, &voxel, ironContent);
        }

        /* Step on the axis where `tmax` is the smallest */
        if (tmax.x < tmax.y) {
            if (tmax.x < tmax.z) {
                pos.x += step.x;
                if (pos.x < 0 || pos.x >= fscale.x) break;
                axis = 0;
                tmax.x += delta.x;
            }
            else {
                pos.z += step.z;
                if (pos.z < 0 || pos.z >= fscale.z) break;
                axis = 2;
                tmax.z += delta.z;
            }
        }
        else {
            if (tmax.y < tmax.z) {
                pos.y += step.y;
                if (pos.y < 0 || pos.y >= fscale.y) break;
                axis = 1;
                tmax.y += delta.y;
            }
            else {
                pos.z += step.z;
                if (pos.z < 0 || pos.z >= fscale.z) break;
                axis = 2;
                tmax.z += delta.z;
            }
        }
    }

    return rayCastMiss;
}